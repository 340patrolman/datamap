def main():
    assert set(MAP) == set(CATS), set(CATS) ^ set(MAP)
    used = set()
    rows = []
    for c in CATS:
        sv, cl, memo = MAP[c]
        for n, r in sv:
            assert n in SVC100, n
            used.add(n)
        for i, r in cl:
            assert 0 <= i < len(CLS), i
        rows.append([c, [[n, r] for n, r in sv], [[i, CLS[i][4], r] for i, r in cl], memo])
    doc = {'schema': 'tg-ind-dict/1', 'made': datetime.datetime.now().strftime('%Y-%m-%d %H:%M'),
           'source': '인허가 30 = tools/region/biz-bake.py CATS(행안부 지방행정인허가 업태 묶음) · 상권분석 100 = 서울시 상권분석서비스 서비스업종(r/<구>/storind.json·trdar.json 이름) · 소분류 247 = data/storecls/cls.json(소상공인시장진흥공단 상가(상권)정보 분류)',
           'fields': 'rows[[인허가 갈래, [[상권분석 업종, 관계]], [[소분류 자리 번호, 소분류 이름, 관계]], 메모]] · 관계 eq 거의 같은 범위 · in 일부(그 갈래 안에 듦) · mix 여러 갈래에 걸침 · svc_none = 인허가 30 어디에도 안 맞댄 상권분석 업종 · ggcard = 맞대지 않음',
           'note': ['이 표는 이름을 보고 손으로 맞댄 것이다(온톨로지 등급 C 맞대어 읽음) — 두 자료의 같은 이름이 같은 가게 묶음이라는 뜻이 아니다',
                    '값을 더하거나 빼는 데 쓰지 말고 「같은 업종을 다른 자료에서 나란히 본다」에만 쓴다 · eq 가 아닌 짝은 화면에 「범위가 다름」을 같이 적는다',
                    '경기 카드 코드(ggcard)는 이번 판에 맞대지 않았다 — 없음',
                    '정본 = tools/onto/inddict-bake.py 의 MAP 표'],
           'keys': CATS, 'rows': rows, 'svc_none': [n for n in SVC100 if n not in used], 'ggcard': None}
    with open(OUT, 'w', encoding='utf-8') as f:
        json.dump(doc, f, ensure_ascii=False, separators=(',', ':'))
    print('ind-dict.json', os.path.getsize(OUT), 'B · 인허가', len(rows), '· 상권분석 맞댐', len(used), '/ 100 · 소분류 맞댐', sum(len(r[2]) for r in rows), '/', len(CLS))


if __name__ == '__main__':
    main()
