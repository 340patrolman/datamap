def sgg_match(sd, sg):
    sido = SIDO[sd]; names = RENAME.get((sd, sg), [sg])
    return [(sido, n2) for n2 in sorted({a[2] for a in ADM if a[1] == sido}) if any(n2 == n or (n2.startswith(n) and n.endswith('시') ) for n in names)]

def stem(n): return re.sub(r'[\d·,]+(?=[동읍면]$)', '', n)
def nm_eq(tok, leg): return leg == tok or leg in (tok + '동', tok + '읍', tok + '면')

def build(rules):   # rules: [(office idx, (시도, 시군구, 방식, 목록))] → {k8: {idx: 무게}}
    W = collections.defaultdict(lambda: collections.defaultdict(float)); unmatched = []
    for oi, (sd, sg, mode, lst) in rules:
        S = sgg_match(sd, sg)
        if not S: unmatched.append(('시군구', oi, sd, sg)); continue
        hitall, kind = set(), ''
        for key in S:
            if not mode:
                for a in ADM:
                    if (a[1], a[2]) == key: W[a[0]][oi] += 100
                continue
            if key in LEG:   # 서울·경기 — 법정동으로 고르고 행정동에 넓이 비율로
                hit = set()
                for ln, al in LEG[key]:
                    m = any(nm_eq(t, ln) for t in lst)
                    if m: hit.update(t for t in lst if nm_eq(t, ln))
                    if m == (mode == '+'):
                        for k8, p in al: W[k8][oi] += p
                hitall |= hit; kind = '법정동'
            else:            # 그 밖 — 행정동 이름(숫자 뗀 줄기)으로
                hit = set()
                for a in ADM:
                    if (a[1], a[2]) != key: continue
                    m = any(nm_eq(t, stem(a[3])) or nm_eq(t, a[3]) for t in lst)
                    if m: hit.update(t for t in lst if nm_eq(t, stem(a[3])) or nm_eq(t, a[3]))
                    if m == (mode == '+'): W[a[0]][oi] += 100
                hitall |= hit; kind = '행정동 이름'
        if mode:
            for t in lst:
                if t not in hitall: unmatched.append((kind, oi, (sd, sg), t))
    return W, unmatched

